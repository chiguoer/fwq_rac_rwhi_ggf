# =================================================================
# [TRAINING - RWHI v7 Feature-Guided Initialization]
# =================================================================
# RWHI v7 核心设计 (基于 gpt-rwhi-v7.txt):
#
# 三层打分场:
#   S(x,y) = C_base + I_radar(x,y) + ε * J(x,y)
#
# I_radar 公式:
#   I_radar = α * log(1 + σ_proc * w_v * w_d)
#   - w_v = 1 + β * sigmoid(|v|/v_ref): 速度权重
#   - w_d = min((d/d_ref)^λ, w_d_max): 距离权重
#
# 残差式空间扩散:
#   S_final = S + γ * (MaxPool3x3(S) - S)
#
# Feature-Guided Initialization:
#   α embedding 注入 Query 特征
#
# 使用方法：
#   训练：python train.py --config configs/racformer_with_rwhi_v53.py
#   测试：python val.py --config configs/racformer_with_rwhi_v53.py --weights checkpoints/xxx.pth
# =================================================================

